; KTEST: test harness TSR for the Ultima I executables (cheat/test layer, not part of the game).
; Hooks INT 21h. AH=06h DL=FFh (the game's key poll) is answered from a script KEYS.BIN;
; the script can also poke bytes into the game's DGROUP and dump DGROUP ranges to files.
; Script ops (bytes):
;   00 k          deliver key k
;   01 s          deliver an extended key (AL=0 now, AL=s on the next poll)
;   02 n          report "no key" for n polls
;   03 off16 len8 bytes...   poke bytes at DS:off (the caller's DGROUP)
;   04 idx8 off16 len16      write DS:off,len to file Dn.BIN (n = idx digit)
;   05            terminate the program (AH=4Ch)
CODE	SEGMENT	PARA
	ASSUME	CS:CODE,DS:CODE
	ORG	0
START:	JMP	INSTALL
OLD	DD	0
GDS	DW	0
SPTR	DW	OFFSET SCRIPT
PEND	DB	0
WAITN	DW	0
DOFF	DW	0
DLEN	DW	0
FNAME	DB	'D0.BIN',0
KNAME	DB	'KEYS.BIN',0
HOOK:	CMP	AH,6
	JE	H1
CHAIN:	JMP	DWORD PTR CS:OLD
H1:	CMP	DL,0FFH
	JNE	CHAIN
	PUSH	BP
	MOV	BP,SP
	PUSH	AX
	PUSH	BX
	PUSH	CX
	PUSH	DX
	PUSH	SI
	PUSH	DI
	PUSH	DS
	PUSH	ES
	MOV	CS:GDS,DS
	PUSH	CS
	POP	DS
L0:	CMP	PEND,0
	JE	L0A
	MOV	AL,PEND
	MOV	PEND,0
	JMP	GOTKEY
L0A:	CMP	WAITN,0
	JE	L1
	DEC	WAITN
	JMP	NOKEY
L1:	MOV	SI,SPTR
	LODSB
	CMP	AL,0
	JE	OPKEY
	CMP	AL,1
	JE	OPEXT
	CMP	AL,2
	JE	OPNONE
	CMP	AL,3
	JE	OPPOKE
	CMP	AL,4
	JE	OPDUMP
	MOV	AX,4C00H
	PUSHF
	CALL	DWORD PTR OLD
OPKEY:	LODSB
	MOV	SPTR,SI
	JMP	GOTKEY
OPEXT:	LODSB
	MOV	SPTR,SI
	MOV	PEND,AL
	XOR	AL,AL
	JMP	GOTKEY
OPNONE:	LODSB
	XOR	AH,AH
	MOV	WAITN,AX
	MOV	SPTR,SI
	JMP	L0
OPPOKE:	LODSW
	MOV	DI,AX
	LODSB
	XOR	CH,CH
	MOV	CL,AL
	MOV	ES,GDS
POKE1:	JCXZ	POKED
	LODSB
	STOSB
	LOOP	POKE1
POKED:	MOV	SPTR,SI
	JMP	L0
OPDUMP:	LODSB
	ADD	AL,'0'
	MOV	FNAME+1,AL
	LODSW
	MOV	DOFF,AX
	LODSW
	MOV	DLEN,AX
	MOV	SPTR,SI
	MOV	AH,3CH
	XOR	CX,CX
	MOV	DX,OFFSET FNAME
	PUSHF
	CALL	DWORD PTR OLD
	JC	DUMPD
	MOV	BX,AX
	MOV	AH,40H
	MOV	CX,DLEN
	MOV	DX,DOFF
	PUSH	DS
	MOV	DS,GDS
	PUSHF
	CALL	DWORD PTR CS:OLD
	POP	DS
	MOV	AH,3EH
	PUSHF
	CALL	DWORD PTR OLD
DUMPD:	JMP	L0
GOTKEY:	AND	WORD PTR [BP+6],0FFBFH
	JMP	RET1
NOKEY:	XOR	AL,AL
	OR	WORD PTR [BP+6],40H
RET1:	MOV	BYTE PTR [BP-2],AL
	POP	ES
	POP	DS
	POP	DI
	POP	SI
	POP	DX
	POP	CX
	POP	BX
	POP	AX
	POP	BP
	IRET
INSTALL:
	MOV	AX,CS
	MOV	DS,AX
	PUSH	ES
	MOV	AX,3521H
	INT	21H
	MOV	WORD PTR OLD,BX
	MOV	WORD PTR OLD+2,ES
	POP	ES
	MOV	AX,3D00H
	MOV	DX,OFFSET KNAME
	INT	21H
	JC	NOSCR
	MOV	BX,AX
	MOV	AH,3FH
	MOV	CX,4000
	MOV	DX,OFFSET SCRIPT
	INT	21H
	MOV	AH,3EH
	INT	21H
NOSCR:	MOV	AX,2521H
	MOV	DX,OFFSET HOOK
	INT	21H
	MOV	DX,OFFSET ENDRES
	ADD	DX,15
	MOV	CL,4
	SHR	DX,CL
	MOV	AX,CS
	MOV	BX,ES
	SUB	AX,BX
	ADD	DX,AX
	MOV	AX,3100H
	INT	21H
SCRIPT	DB	4000 DUP (5)
ENDRES	LABEL	BYTE
CODE	ENDS
	END	START
